        stairsBlock((StairBlock) BlockRegistry.MAPLE_STAIRS.get(), texture("plank_maple"));
        stairsBlock((StairBlock) BlockRegistry.BAMBOO_PLANK_STAIRS.get(), texture("plank_bamboo"));
        stairsBlock((StairBlock) BlockRegistry.BAMBOO_STAIRS.get(), texture("bamboo_block"));
        stairsBlock((StairBlock) BlockRegistry.BAMBOO_STAIRS_SUNBURNT.get(), texture("bamboo_block_sunburnt"));
