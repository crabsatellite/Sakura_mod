        simpleBlock(BlockRegistry.FALLEN_LEAVES_YELLOW.get(),
                models().getExistingFile(new ResourceLocation("sakura:block/fallen_leaves_yellow")));
        simpleBlock(BlockRegistry.FALLEN_LEAVES_ORANGE.get(),
                models().getExistingFile(new ResourceLocation("sakura:block/fallen_leaves_orange")));
